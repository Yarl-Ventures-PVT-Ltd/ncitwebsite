/**
 * Measures every article image and records which ones are too small to work as
 * a social card.
 *
 * Facebook drops an image under 200px on either side entirely, and renders a
 * small square thumbnail rather than a wide card under 600x315. X needs
 * 300x157 for summary_large_image. Seven of the migrated article images fall
 * under those floors, and two fall under the 200px floor, so those shares
 * currently render with no image at all.
 *
 * The originals do not exist at a larger size: the WordPress export kept only
 * the resized derivatives. So the fix is a fallback to the branded card, and
 * this file records which articles need it rather than measuring 59 files on
 * every build.
 *
 * Regenerate with: node scripts/build-social-images.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { execSync } from "node:child_process";

const MIN_WIDTH = 600;
const MIN_HEIGHT = 315;

const source = fs.readFileSync("src/lib/mock-data/insights.ts", "utf8");
const blocks = source.split(/\n {2}\{\n/).slice(1);

const tooSmall = [];
const sizes = [];
let measured = 0;
let missing = 0;

for (const block of blocks) {
    const slug = block.match(/slug: "([^"]+)"/)?.[1];
    const image = block.match(/imageUrl: "([^"]+)"/)?.[1];
    if (!slug || !image) continue;

    const file = path.join("public", image);
    if (!fs.existsSync(file)) {
        missing += 1;
        console.warn(`  missing on disk: ${image}`);
        continue;
    }

    const out = execSync(`sips -g pixelWidth -g pixelHeight "${file}" 2>/dev/null || true`).toString();
    const width = Number(out.match(/pixelWidth:\s*(\d+)/)?.[1] ?? 0);
    const height = Number(out.match(/pixelHeight:\s*(\d+)/)?.[1] ?? 0);
    if (!width || !height) continue;

    measured += 1;
    sizes.push({ slug, width, height });
    if (width < MIN_WIDTH || height < MIN_HEIGHT) {
        tooSmall.push({ slug, width, height });
    }
}

tooSmall.sort((a, b) => a.slug.localeCompare(b.slug));
sizes.sort((a, b) => a.slug.localeCompare(b.slug));

const body = `// Generated by scripts/build-social-images.mjs. Do not edit by hand.
//
// Articles whose own image is below ${MIN_WIDTH}x${MIN_HEIGHT} and therefore cannot render a
// wide social card. These fall back to the branded share image so the link
// still previews with something, rather than with nothing.
export const ARTICLES_WITHOUT_A_SOCIAL_IMAGE = new Set<string>([
${tooSmall.map((a) => `    "${a.slug}", // ${a.width}x${a.height}`).join("\n")}
]);

// Real pixel dimensions of each article image. Declaring width and height on
// og:image means a scraper can lay the card out without downloading the file,
// which is the usual reason a first share renders with no picture.
export const ARTICLE_IMAGE_SIZE: Record<string, { width: number; height: number }> = {
${sizes.map((a) => `    "${a.slug}": { width: ${a.width}, height: ${a.height} },`).join("\n")}
};
`;

fs.writeFileSync("src/lib/social-images.ts", body);
console.log(`measured ${measured} article images, ${missing} missing on disk`);
console.log(`below ${MIN_WIDTH}x${MIN_HEIGHT}: ${tooSmall.length}`);
for (const a of tooSmall) console.log(`  ${a.width}x${a.height}  ${a.slug}`);
